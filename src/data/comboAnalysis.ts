export interface ComboAnalysis {
  work1Type: string;
  work2Type: string;
  catchcopy: string;
  description: string;
  motivators: string[];
  demotivators: string[];
  goodSigns: string[];
  badSigns: string[];
  helpfulActions: string;
  teamRole: string;
}

function combo(
  w1: string,
  w2: string,
  catchcopy: string,
  description: string,
  motivators: string[],
  demotivators: string[],
  goodSigns: string,
  badSigns: string,
  helpfulActions: string,
  teamRole: string,
): ComboAnalysis {
  return {
    work1Type: w1,
    work2Type: w2,
    catchcopy,
    description,
    motivators,
    demotivators,
    goodSigns: goodSigns.split('・').map((s) => s.trim()).filter(Boolean),
    badSigns: badSigns.split('・').map((s) => s.trim()).filter(Boolean),
    helpfulActions,
    teamRole,
  };
}

